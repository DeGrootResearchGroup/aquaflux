#!/usr/bin/env bash
# Run one study arm of this case through validation/run_case.sh and keep what it produced.
#
#   validation/bfs3d_openfoam/run_arm.sh <arm> [VAR=VALUE ...]
#
# The arm is compare.py with the given environment (BFS3D_* overrides, AQUAFLUX_* switches). Its march
# log, run log, report, figure and checkpoints are copied to arms/<arm>/ (gitignored), with config.txt
# recording the overrides, the commit and the exit status, and the tracked report.md and figure are
# restored afterwards so a study leaves the tree clean. Summarize finished arms with
#
#   python3 validation/bfs3d_openfoam/march_log_compare.py --table validation/bfs3d_openfoam/arms/*/march.log
#
# Chain arms with `;` in one background shell, so they run one at a time:
#
#   R=validation/bfs3d_openfoam/run_arm.sh; $R grow2 BFS3D_GROW=2; $R stations18 BFS3D_RAMP_STATIONS=18
#
# Two things it does beyond run_case.sh, both because studies here share one machine with other
# sessions' cases:
#   - It QUEUES rather than failing when another case holds the slot: it waits on
#     `run_case.sh --running`, and launches again if another case slips in first. run_case.sh refuses
#     a second case, which is right, but a chain of arms would otherwise lose every arm after the refusal.
#   - It HOLDS before launching while arms/HOLD exists (`touch` it to pause a chain between arms, e.g.
#     so a test tier can run; remove it to resume). The arm already running is not affected.
#
# Pass every VAR=VALUE as its own argument. A variable holding several assignments (G="A=1 B=2"; $R arm
# $G) is ONE word under zsh, which does not split unquoted parameters, so env would set A to "1 B=2".
#
# Do not edit this file while a chain is running: bash reads a script as it executes, so the chain's
# current invocation would resume at a stale byte offset.
set -u
cd "$(dirname "$0")/../.."
CASE=validation/bfs3d_openfoam
arm=${1:?usage: run_arm.sh <arm> [VAR=VALUE ...]}
shift
dest=$CASE/arms/$arm
mkdir -p "$dest"
while [ -f $CASE/arms/HOLD ]; do sleep 30; done
rm -f $CASE/checkpoints/state-*
echo "=== $arm: $* commit $(git rev-parse --short HEAD) $(date)" | tee "$dest/config.txt"
while :; do
  while validation/run_case.sh --running >/dev/null; do sleep 30; done
  out=$(mktemp)
  # Teed so the refusal can be recognized; the status is run_case.sh's own (PIPESTATUS), never tee's.
  env "$@" validation/run_case.sh $CASE/compare.py --wait 2>&1 | tee "$out"
  status=${PIPESTATUS[0]}
  grep -q "ALREADY running" "$out" || break
  rm -f "$out"
done
rm -f "$out"
cp $CASE/march.log "$dest/march.log"
ls -t $CASE/run-*.log | head -1 | xargs -I{} cp {} "$dest/"
cp $CASE/report.md $CASE/figures/comparison.png "$dest/" 2>/dev/null
mkdir -p "$dest/checkpoints" && cp $CASE/checkpoints/* "$dest/checkpoints/" 2>/dev/null
git checkout -- $CASE/report.md $CASE/figures/comparison.png 2>/dev/null
echo "=== $arm exit $status $(date)" | tee -a "$dest/config.txt"
exit $status
