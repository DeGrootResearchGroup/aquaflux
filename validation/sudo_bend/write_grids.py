FILES = {
    "mesh.yaml": MESH,
    "precursor_mesh.yaml": PRECURSOR_MESH,
    "precursor.yaml": PRECURSOR,
    "case.yaml": CASE,
}


def levels() -> list[Level]:
    """The study's grids, coarse to fine."""
    return [Level(n, k) for k, n in enumerate(ROUND)]


def main() -> None:
    for level in levels():
        directory = GRIDS / level.name
        directory.mkdir(parents=True, exist_ok=True)
        settings = level.settings()
        for name, template in FILES.items():
            (directory / name).write_text(template.format(**settings))
        print(
            f"{level.name}: max_size {settings['max_size']}, layers {settings['layers']} x "
            f"{settings['layer_growth']}, rows {settings['row_growth']} to {settings['longest_row']}",
            flush=True,
        )


if __name__ == "__main__":
    main()
